    fun pref(code: Int) = PREFS.first { it.code == code }

    // ---------------------------------------------------------------- かたち

    class Shape(val code: Int, val polys: List<FloatArray>, val cx: Float, val cy: Float) {
        val minX = polys.minOf { p -> (p.indices step 2).minOf { p[it] } }
        val maxX = polys.maxOf { p -> (p.indices step 2).maxOf { p[it] } }
        val minY = polys.minOf { p -> (1 until p.size step 2).minOf { p[it] } }
        val maxY = polys.maxOf { p -> (1 until p.size step 2).maxOf { p[it] } }
    }

    class Map(val w: Float, val h: Float, val inset: FloatArray, val shapes: List<Shape>)

    private var map: Map? = null

    fun map(c: Context): Map = map ?: JSONObject(c.assets.open("japan/map.json").bufferedReader().readText()).let { o ->
        val prefs = o.getJSONArray("prefs")
        Map(
            o.getDouble("w").toFloat(), o.getDouble("h").toFloat(),
            o.getJSONArray("inset").let { a -> FloatArray(4) { a.getDouble(it).toFloat() } },
            (0 until prefs.length()).map { i ->
                val p = prefs.getJSONObject(i)
                val polys = p.getJSONArray("polys").let { a -> (0 until a.length()).map { j -> a.getJSONArray(j).let { r -> FloatArray(r.length()) { r.getDouble(it).toFloat() } } } }
                Shape(p.getInt("code"), polys, p.getDouble("cx").toFloat(), p.getDouble("cy").toFloat())
            },
        )
    }.also { map = it }
